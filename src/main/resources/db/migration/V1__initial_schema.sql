-- Initial BuildTrack schema.
-- Matches the tables Hibernate created before Flyway was introduced, so existing
-- databases are baselined at version 1 and new databases are built from this file.

CREATE TABLE app_users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL,
    email    VARCHAR(255) NOT NULL,
    password VARCHAR(255) NOT NULL,
    role     VARCHAR(255) NOT NULL,
    CONSTRAINT uk_app_users_username UNIQUE (username),
    CONSTRAINT uk_app_users_email    UNIQUE (email),
    CONSTRAINT ck_app_users_role     CHECK (role IN ('USER', 'ADMIN'))
);

CREATE TABLE customers (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(255),
    email VARCHAR(255),
    phone VARCHAR(255)
);

CREATE TABLE projects (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                     VARCHAR(255),
    description              VARCHAR(255),
    address                  VARCHAR(255),
    start_date               DATE,
    expected_completion_date DATE,
    status                   VARCHAR(255),
    customer_id              BIGINT,
    CONSTRAINT fk_projects_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
    CONSTRAINT ck_projects_status
        CHECK (status IN ('PLANNING', 'IN_PROGRESS', 'ON_HOLD', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE tasks (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255),
    description VARCHAR(255),
    status      VARCHAR(255),
    due_date    DATE,
    project_id  BIGINT,
    CONSTRAINT fk_tasks_project FOREIGN KEY (project_id) REFERENCES projects (id),
    CONSTRAINT ck_tasks_status
        CHECK (status IN ('NOT_STARTED', 'IN_PROGRESS', 'BLOCKED', 'COMPLETED', 'CANCELLED'))
);

CREATE INDEX idx_projects_customer_id ON projects (customer_id);
CREATE INDEX idx_tasks_project_id ON tasks (project_id);
